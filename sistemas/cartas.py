@dataclass(frozen=True)
class Carta:
    id: str
    nome: str
    categoria: str
    tipo: str
    poder: int
    raridade: str
    custo: int
    habilidade: str
    descricao: str = ""
    jogo_origem: str = ""

    def para_dict(self) -> dict[str, Any]:
        data = asdict(self)
        faccoes = {"Força": "Ordem Áurea", "Destreza": "Império Nocturno", "Magia": "Conclave da Ruína"}
        fileiras = {"Força": "melee", "Destreza": "ranged", "Magia": "siege"}
        especial = str(self.categoria or "").casefold() == "especial"
        faccao = faccoes.get(self.tipo, "Ordem Áurea")
        fileira = fileiras.get(self.tipo, "melee")
        data.update({"categoria": "Especial" if especial else "Unidade", "faccao": faccao, "fileira": fileira, "categoria_arte": "Especial" if especial else "Unidade", "categoria_origem": "Especial" if especial else "Unidade", "jogo_origem": ""})
        return data

